const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('api', {
  getMusicDir:      ()        => ipcRenderer.invoke('get-music-dir'),
  loadCache:        ()        => ipcRenderer.invoke('load-cache'),
  saveCache:        (cache)   => ipcRenderer.invoke('save-cache', cache),
  scanMusic:        ()        => ipcRenderer.invoke('scan-music'),
  readMeta:         (path)    => ipcRenderer.invoke('read-meta', path),
  lastfmStatus:     ()        => ipcRenderer.invoke('lastfm-status'),
  lastfmSetKey:     (key)     => ipcRenderer.invoke('lastfm-set-key', key),
  lastfmCached:     ()        => ipcRenderer.invoke('lastfm-cached'),
  lastfmTags:       (q)       => ipcRenderer.invoke('lastfm-tags', q),
  lastfmSimilar:    (q)       => ipcRenderer.invoke('lastfm-similar', q),
  openExternal:     (url)     => ipcRenderer.send('open-external', url),
  geminiStatus:     ()        => ipcRenderer.invoke('gemini-status'),
  geminiSetKey:     (key)     => ipcRenderer.invoke('gemini-set-key', key),
  djSay:            (text, engine, fast) => ipcRenderer.invoke('dj-say', text, engine, fast),
  djCached:         (text)    => ipcRenderer.invoke('dj-cached', text),
  djThink:          (sys, prompt, schema) => ipcRenderer.invoke('dj-think', sys, prompt, schema),
  audioCached:      ()        => ipcRenderer.invoke('audio-cached'),
  audioAnalyze:     (files)   => ipcRenderer.invoke('audio-analyze', files),
  onAudioResult:    (cb)      => ipcRenderer.on('audio-result', (_, m) => cb(m)),
  onAudioProgress:  (cb)      => ipcRenderer.on('audio-progress', (_, m) => cb(m)),
  winClose:         ()        => ipcRenderer.send('win-close'),
  winMinimize:      ()        => ipcRenderer.send('win-minimize'),
  winMaximize:      ()        => ipcRenderer.send('win-maximize'),
  onLibraryChanged: (cb)      => ipcRenderer.on('library-changed', cb),
})
